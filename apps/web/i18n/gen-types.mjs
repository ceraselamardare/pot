#!/usr/bin/env node
// Generates i18n/messages.d.ts from en.json (frontend-architecture §9.2). `--check` fails when the committed
// file is stale (wired into `pnpm lint`). Placeholders `{name}` become `string | number` vars; plural keys
// (`key#one` / `key#other`) become `key` with `n: number`.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const PLACEHOLDER = /\{(\w+)\}/g

/** @param {Record<string, string>} messages */
export function buildTypes(messages) {
  /** @type {Map<string, Map<string, string>>} */
  const keys = new Map()
  for (const [rawKey, value] of Object.entries(messages)) {
    const [key, plural] = rawKey.split("#")
    const vars = keys.get(key) ?? new Map()
    for (const m of value.matchAll(PLACEHOLDER)) vars.set(m[1], vars.get(m[1]) ?? "string | number")
    if (plural) vars.set("n", "number")
    keys.set(key, vars)
  }
  const lines = [...keys.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([key, vars]) => {
      if (vars.size === 0) return `  ${JSON.stringify(key)}: undefined`
      const fields = [...vars.entries()].map(([v, ty]) => `${v}: ${ty}`).join("; ")
      return `  ${JSON.stringify(key)}: { ${fields} }`
    })
  return [
    "// GENERATED by i18n/gen-types.mjs from i18n/en.json. Do not edit by hand: run `pnpm --filter web i18n:gen`.",
    "export interface Messages {",
    ...lines,
    "}",
    "",
  ].join("\n")
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const src = fileURLToPath(new URL("./en.json", import.meta.url))
  const out = fileURLToPath(new URL("./messages.d.ts", import.meta.url))
  const next = buildTypes(JSON.parse(readFileSync(src, "utf8")))
  if (process.argv.includes("--check")) {
    let current = ""
    try {
      current = readFileSync(out, "utf8")
    } catch {}
    if (current !== next) {
      console.error("i18n: messages.d.ts is stale. Run `pnpm --filter web i18n:gen`.")
      process.exit(1)
    }
    console.log("i18n: messages.d.ts is up to date")
  } else {
    writeFileSync(out, next)
    console.log("i18n: wrote messages.d.ts")
  }
}
