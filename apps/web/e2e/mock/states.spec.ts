// Degraded and edge states (M-10, M-15, M-05, M-21 c): offline banner + disabled money CTAs, revert-with-toast,
// reduced motion (no burst, the 1.2 s beat stays), inline approve with Undo, Appearance switching.
import { expect, test } from "@playwright/test"
import { asPersona, openedSheet, typeAmount } from "../fixtures/pot"

test("offline: banner, cached numbers stay, money buttons explain; back online", async ({ page, context }) => {
  await asPersona(page, "maya")
  await page.goto("/p/lisbon-trip")
  await expect(page.locator("[data-hero] [data-money]")).toHaveText("$450.00")
  await context.setOffline(true)
  await expect(page.getByText("You're offline. You can look around; adding money and approving need a connection.")).toBeVisible()
  await expect(page.locator("[data-hero] [data-money]")).toHaveText("$450.00")
  const add = page.getByRole("button", { name: "Add money" })
  await expect(add).toHaveAttribute("aria-disabled", "true")
  await add.click({ force: true }) // aria-disabled, but tapping explains why (ux-spec 4.20)
  await expect(page.getByText("You're offline. Connect to add money.")).toBeVisible()
  await expect(page.getByRole("dialog")).toBeHidden()
  await context.setOffline(false)
  await expect(page.locator("[data-offline-banner]")).toBeHidden()
  await expect(page.getByText("Back online")).toBeVisible()
})

test("a failed add reverts the Sending… item and says what happened (one toast)", async ({ page }) => {
  await asPersona(page, "maya")
  await page.addInitScript(() => localStorage.setItem("pot.mock.fail", "add"))
  await page.goto("/p/lisbon-trip?sheet=add")
  const sheet = await openedSheet(page, "Add money to Lisbon Trip")
  await typeAmount(page, "50")
  await sheet.getByRole("button", { name: "Add $50" }).click()
  await expect(page.getByText("Adding $50…")).toBeVisible()
  await expect(page.getByText("We couldn't add your money right now. Nothing left your account. Try again in a minute.")).toBeVisible()
  await expect(page.getByText("Adding $50…")).toBeHidden()
  await expect(page.getByText("+$50 on the way")).toBeHidden()
  await expect(page.locator("[data-hero] [data-money]")).toHaveText("$450.00")
})

test.describe("reduced motion", () => {
  test.use({ reducedMotion: "reduce" })
  test("no burst and still dots, but the 1.2 s rules beat stays", async ({ page }) => {
    await asPersona(page, "maya")
    await page.goto("/p/lisbon-trip?sheet=spend")
    const sheet = await openedSheet(page, "Spend from Lisbon Trip")
    await typeAmount(page, "20")
    await sheet.getByRole("button", { name: "Get $20 back" }).click()
    await expect(sheet.getByText("Checking Pot rules…")).toBeVisible()
    const t0 = Date.now()
    const running = await sheet.locator("[data-typing-dots] .pot-dot").first().evaluate((el) => el.getAnimations().length)
    expect(running).toBe(0)
    await expect(sheet.locator("[data-capsule]").getByText("Approved by Pot rules")).toBeVisible()
    expect(Date.now() - t0).toBeGreaterThanOrEqual(1000)
    await expect(sheet.locator("[data-celebration]")).toHaveCount(0)
    await expect(sheet.getByText("$20 sent to you")).toBeVisible()
  })
})

test("inline Approve: 4 s Undo sends nothing", async ({ page }) => {
  await asPersona(page, "maya")
  await page.goto("/p/lisbon-trip?sheet=spend")
  const sheet = await openedSheet(page, "Spend from Lisbon Trip")
  await typeAmount(page, "300")
  await sheet.getByRole("button", { name: "Ask the group" }).click()
  await sheet.getByRole("button", { name: "Done" }).click()
  await page.getByRole("button", { name: "You're Maya" }).click()
  await page.getByRole("menuitem", { name: "Switch to Leo" }).click()
  const card = page.locator("[data-request-card]").locator("visible=true").first()
  await card.getByRole("button", { name: "Approve $300" }).click()
  await expect(card.getByText("Approved", { exact: true })).toBeVisible()
  await card.getByRole("button", { name: "Undo" }).click()
  await expect(card.getByRole("button", { name: "Approve $300" })).toBeVisible()
  await page.waitForTimeout(4500)
  await expect(page.locator("[data-hero] [data-money]")).toHaveText("$450.00")
  await expect(card.getByText("1 of 2 approvals")).toBeVisible()
})

test("Appearance: Night and Day switch live and survive a reload; Match my phone restores", async ({ page }, info) => {
  await asPersona(page, "maya")
  await page.goto("/you")
  const group = page.getByRole("radiogroup", { name: "Appearance" })
  await group.getByRole("radio", { name: "Night" }).click()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "night")
  expect(await page.evaluate(() => getComputedStyle(document.body).backgroundColor)).toBe("rgb(28, 20, 36)")
  await page.reload()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "night")
  await expect(group.getByRole("radio", { name: "Night" })).toHaveAttribute("aria-checked", "true")
  await group.getByRole("radio", { name: "Day" }).click()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "day")
  await group.getByRole("radio", { name: "Match my phone" }).click()
  await expect(group.getByRole("radio", { name: "Match my phone" })).toHaveAttribute("aria-checked", "true")
  await expect(page.locator("html")).toHaveAttribute("data-theme", info.project.use.colorScheme === "dark" ? "night" : "day")
})

test("a cold deep link to a request opens the Pot with the Approve sheet; closing stays in the app", async ({ page }) => {
  await asPersona(page, "maya")
  await page.goto("/p/lisbon-trip?sheet=spend")
  const sheet = await openedSheet(page, "Spend from Lisbon Trip")
  await typeAmount(page, "300")
  await sheet.getByRole("button", { name: "Ask the group" }).click()
  await expect(sheet.getByText("Sent to the group")).toBeVisible()
  await page.goto("/p/lisbon-trip?r=12")
  const approve = await openedSheet(page, "Maya asks for $300")
  await expect(approve.getByText("Your approval is counted. Waiting for 1 more.")).toBeVisible()
  await approve.getByRole("button", { name: "Close" }).click()
  await expect(page).toHaveURL(/\/p\/lisbon-trip$/)
  await expect(page.getByRole("heading", { level: 1, name: "Lisbon Trip" })).toBeVisible()
})
