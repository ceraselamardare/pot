// Writes apps/web/.env.local (gitignored) for the PREVIEW testnet environment: public ids from the account
// map + the hot keys from apps/web/.keys/preview.env. Prints names only, never values of secrets.
//   scripts/run env            (re-run after `keys init`; keeps any line you added below the marker)
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { ENV_LOCAL, IDS, KEYS_FILE, parseEnvFile } from "./lib/env.ts"

const MARK = "# ---- local additions below this line are kept by scripts/run env ----"
if (!existsSync(KEYS_FILE)) throw new Error("run `scripts/run keys init` first")
const keys = parseEnvFile(readFileSync(KEYS_FILE, "utf8"))
const kept = existsSync(ENV_LOCAL) ? (readFileSync(ENV_LOCAL, "utf8").split(MARK)[1] ?? "\n") : "\n"

const pub: [string, string][] = [
  ["NEXT_PUBLIC_NETWORK", "testnet"],
  ["NEXT_PUBLIC_APP_URL", "http://localhost:3000"],
  ["NEXT_PUBLIC_HUB_ID", IDS.hub],
  ["NEXT_PUBLIC_USDC_ID", IDS.usdc],
  ["NEXT_PUBLIC_RPC_URLS", "https://rpc.testnet.fastnear.com,https://near-testnet.drpc.org"],
  ["NEXT_PUBLIC_TX_API", "https://tx.test.fastnear.com"],
  ["NEXT_PUBLIC_EXPLORER", "https://testnet.nearblocks.io"],
  ["NEXT_PUBLIC_FLAG_DEV_SESSION", "true"],
  ["NEXT_PUBLIC_FLAG_DEMO", "true"],
  ["FLAG_DEV_SESSION", "true"],
  ["FLAG_DEMO", "true"],
  ["RELAYER_ACCOUNT_ID", IDS.relayer],
  ["TREASURY_ACCOUNT_ID", IDS.treasury],
  ["DEMO_REFERENCE_POT", `lisbon-trip.${IDS.hub}`],
  ["DEMO_POOL_TARGET", "3"],
  ["MPC_SIGN_DEPOSIT_YOCTO", "1"],
  // the preview relayer holds ≈ 2.5 NEAR, so the api-spec 1/2/5 thresholds are scaled down
  ["RELAYER_FLOOR_NEAR", "0.3"],
  ["RELAYER_CRITICAL_NEAR", "0.6"],
  ["RELAYER_WARN_NEAR", "1"],
  // local-dev quota headroom for repeated live/e2e runs (api-spec §3.5 preview defaults are 10 Pots/day, 10 dev accounts per IP)
  ["QUOTA_GLOBAL_POTS_CREATED", "40"],
  ["QUOTA_GLOBAL_DEV_ACCOUNTS", "60"],
  ["QUOTA_IP_DEV_ACCOUNTS", "60"],
  ["QUOTA_IP_FAUCET_USD", "20000000000"], // $20k/day per IP (one laptop runs the live tests, the e2e and Playwright)
  ["DATABASE_URL", "postgres://pot:pot@localhost:54329/pot"],
  ["DATABASE_URL_UNPOOLED", "postgres://pot:pot@localhost:54329/pot"],
  ["DATABASE_URL_TEST", "postgres://pot:pot@localhost:54329/pot_test"],
]
const secrets = ["RELAYER_KEYS", "TREASURY_KEYS", "DEMO_PERSONA_KEY", "APP_HMAC_SECRET"]
const lines = [
  "# PREVIEW testnet env for apps/web (gitignored). Generated by scripts/run env from notes/deploy.md's account map",
  "# and apps/web/.keys/preview.env. Never commit; never paste the [secret] values anywhere.",
  ...pub.map(([k, v]) => `${k}=${v}`),
  "# [secret] preview hot keys (testnet only)",
  ...secrets.map((k) => `${k}=${keys[k] ?? ""}`),
  MARK,
]
writeFileSync(ENV_LOCAL, lines.join("\n") + kept, { mode: 0o600 })
console.log(`wrote ${ENV_LOCAL.pathname}: ${pub.map(([k]) => k).join(", ")}, ${secrets.join(", ")} (secrets not shown)`)
