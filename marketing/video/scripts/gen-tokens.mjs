// Generates src/brand/tokens.ts from the brand's single source of truth (brand/tokens.json).
// Run from marketing/video: node scripts/gen-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../../../brand/tokens.json", import.meta.url), "utf8"));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const day = {};
const night = {};
for (const t of src.color.tokens) {
  day[camel(t.name)] = t.value.day;
  night[camel(t.name)] = t.value.night;
}
const pick = (group) => Object.fromEntries(src[group].tokens.map((t) => [camel(t.name), parseFloat(t.value)]));
const shadow = (theme) => Object.fromEntries(src.shadow.tokens.map((t) => [camel(t.name), t.value[theme]]));
const typeStyles = {};
for (const g of src.type.groups) {
  for (const s of g.styles) {
    typeStyles[camel(s.name)] = {
      family: g.family,
      fontSize: parseFloat(s.fontSize),
      lineHeight: parseFloat(s.lineHeight),
      fontWeight: s.fontWeight,
      letterSpacing: s.letterSpacing ?? "0",
    };
  }
}

const out = `// GENERATED by scripts/gen-tokens.mjs from brand/tokens.json. Do not edit by hand.
// Colours: use ONLY these. Marigold (brand) is never a text colour.

export const day = ${JSON.stringify(day, null, 2)} as const;

export const night = ${JSON.stringify(night, null, 2)} as const;

export type Theme = typeof day;

export const space = ${JSON.stringify(pick("spacing"), null, 2)} as const;

export const radius = ${JSON.stringify(pick("radius"), null, 2)} as const;

export const layout = ${JSON.stringify(pick("layout"), null, 2)} as const;

export const shadow = {
  day: ${JSON.stringify(shadow("day"), null, 2)},
  night: ${JSON.stringify(shadow("night"), null, 2)},
} as const;

/** Type styles in px (designed at a 390 px wide phone). family: "display" = Gabarito, "sans" = Figtree. */
export const typeStyles = ${JSON.stringify(typeStyles, null, 2)} as const;

/** Member avatar colours in join order: Maya = member1, Sam = member2, Leo = member3. */
export const members = [day.member1, day.member2, day.member3, day.member4, day.member5, day.member6] as const;
`;
writeFileSync(new URL("../src/brand/tokens.ts", import.meta.url), out);
console.log("wrote src/brand/tokens.ts");
